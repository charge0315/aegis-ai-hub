/**
 * カテゴリ名を正規化します。
 * 
 * 【設計思想】
 * AI（LLM）が生成するカテゴリ名は、時に全角・半角の混在や、不要な記号、
 * スペースの有無といった「表記揺れ」を含みます。
 * これをそのままキーとして使用すると、ユーザーが定義した既存カテゴリと
 * 紐付かず、ダッシュボード上で別のカテゴリとして重複表示される副作用が生じます。
 * 
 * 本関数は、それらのノイズを除去して「意味的な同一性」を担保し、
 * データの整合性を維持することを目的としています。
 */
export const normalizeCategoryName = (name: string): string => {
  // 記号（＆, &, ・）や空白を除去し、すべて小文字に統一します。
  return name.replace(/[＆&＆\s・]/g, '').toLowerCase();
};

/**
 * 下位互換性のためのエイリアス
 */
export const clean = normalizeCategoryName;
